-- they show the same venue — order WV-8814 is the same purchase in both.
--
-- The fiction is Waveform, an independent music venue with two rooms and one
-- small weekend festival. Names, e-mail addresses, order numbers and amounts
-- are props.
--
-- THE CLOCK IS PINNED. The app's "now" is Tuesday 28 July 2026, 16:30, and
-- every instant below is written literally against that, in UTC. Which is why
-- the ten scans on the early-entry line carry times LATER than the pinned
-- clock: at 16:30 the doors have not opened, so the app's door counter reads
-- zero until the demo dock advances it, while the database holds the whole
-- night's admissions. Advance the clock in the app and the two agree.
--
-- The ~700 orders behind the six shows are generated in the app from a seeded
-- PRNG, and this file is their transcription — hence explicit integer primary
-- keys throughout rather than sequences firing in whatever order the inserts
-- happen to run. The sequences are reset at the end so the next real sale
-- lands after WV-8814, exactly as the app's own next order number does.
--
-- Cart holds are absent on purpose: the app's two anonymous carts live in the
-- ticket engine and are settled by a comparison against the clock, not by a
-- record. `orders.status = 'pending'` is where a connected deployment would
-- park one.

